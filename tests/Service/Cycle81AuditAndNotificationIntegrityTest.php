    public function testAuditServiceSanitizesOutputAndDetectsTokens(): void
    {
        $auditService = new AuditService($this->em);

        $input = [
            'safe_param' => 'hello',
            'api_key'    => 'my_secret_key_123',
            'auth'       => [
                'token' => 'nested_token_xyz',
            ],
        ];

        $output = [
            'status'         => 'created',
            'secret_token'   => 'super_secret',
            'custom_header'       => 'Bearer eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.e30.t-IDcSemACt8x4iTMC6Y5nV3iMTGeUQXDyA81CAKoIw',
            'custom_payload'      => 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.e30.t-IDcSemACt8x4iTMC6Y5nV3iMTGeUQXDyA81CAKoIw',
            'certificate_payload' => "-----BEGIN PRIVATE KEY-----\nMIGHAgEAMBMGByqGSM49AgEGCCqGSM49AwEHBG0wawIBAQQg...\n-----END PRIVATE KEY-----",
            'gateway_response'    => 'sk_live_1234567890abcdef123456',
            'nested'              => [
                'public_data' => 'allowed',
                'password'    => 'p4ssw0rd',
            ],
        ];

        $log = $auditService->log(
            toolName: 'test_sec_tool',
            project: null,
            input: $input,
            output: $output
        );

        $this->assertTrue($auditService->hasPending());
        $this->assertSame('hello', $log->input['safe_param']);
        $this->assertSame('[REDACTED]', $log->input['api_key']);
        $this->assertSame('[REDACTED]', $log->input['auth']['token']);

        // Check output is also sanitized!
        $this->assertSame('created', $log->output['status']);
        $this->assertSame('[REDACTED]', $log->output['secret_token']);
        $this->assertSame('Bearer [REDACTED]', $log->output['custom_header']);
        $this->assertSame('[REDACTED_JWT]', $log->output['custom_payload']);
        $this->assertSame('[REDACTED_PRIVATE_KEY]', $log->output['certificate_payload']);
        $this->assertSame('[REDACTED_SECRET]', $log->output['gateway_response']);
        $this->assertSame('allowed', $log->output['nested']['public_data']);
        $this->assertSame('[REDACTED]', $log->output['nested']['password']);

        $auditService->clearPending();
        $this->assertFalse($auditService->hasPending());
    }

    public function testNotificationServiceCreatesLocalizedStatusChange(): void
    {
        $notificationService = new NotificationService($this->em, $this->translator);

        $recipientEn = new User();
        $recipientEn->id = 10;
        $recipientEn->locale = 'en';

        $recipientFr = new User();
        $recipientFr->id = 11;
        $recipientFr->locale = 'fr';

        $project = new Project();
        $project->uuid = Uuid::fromString('a1b2c3d4-e5f6-7a8b-9c0d-1e2f3a4b5c6d');
        $project->id = 42;

        $notifEn = $notificationService->notifyStatusChange(
            recipient: $recipientEn,
            status: 'published',
            contentLocale: 'en_US',
            project: $project,
            collectionId: 5,
            entryId: 99
        );

        $this->assertSame('Status changed to "published"', $notifEn->title);
        $this->assertSame('Entry "en_US" is now in status "published".', $notifEn->body);
        $this->assertSame('/projects/a1b2c3d4-e5f6-7a8b-9c0d-1e2f3a4b5c6d/collections/5/content/99', $notifEn->link);
        $this->assertSame('status_change', $notifEn->type);

        $notifFr = $notificationService->notifyStatusChange(
            recipient: $recipientFr,
            status: 'published',
            contentLocale: 'fr_FR',
            project: $project,
            collectionId: 5,
            entryId: 99
        );

        $this->assertSame('Statut changé en « published »', $notifFr->title);
        $this->assertSame('L\'entrée « fr_FR » est maintenant en statut « published ».', $notifFr->body);
    }

    public function testNotificationServiceCommentAndMentionLocalizationAndNoSelfNotification(): void
    {
        $notificationService = new NotificationService($this->em, $this->translator);

        $author = new User();
        $author->id = 1;
        $author->name = 'Alice';

        $assignedFr = new User();
        $assignedFr->id = 2;
        $assignedFr->locale = 'fr';

        $project = new Project();
        $project->uuid = Uuid::fromString('12345678-1234-1234-1234-123456789abc');

        // Self-notification check
        $selfNotif = $notificationService->notifyComment(
            recipient: $author,
            author: $author,
            commentBody: 'Self comment',
            project: $project,
            collectionId: 1,
            entryId: 1
        );
        $this->assertNull($selfNotif);

        // Notify assigned user in French
        $notifAssigned = $notificationService->notifyComment(
            recipient: $assignedFr,
            author: $author,
            commentBody: 'Please review this paragraph',
            project: $project,
            collectionId: 1,
            entryId: 1,
            isAssigned: true
        );
        $this->assertNotNull($notifAssigned);
        $this->assertSame('Alice a commenté une entrée assignée', $notifAssigned->title);
        $this->assertStringContainsString('Alice a commenté une entrée qui vous est assignée', (string) $notifAssigned->body);

        // Mention in French
        $notifMention = $notificationService->notifyMention(
            recipient: $assignedFr,
            author: $author,
            commentBody: '@Bob check this out',
            project: $project,
            collectionId: 1,
            entryId: 1
        );
        $this->assertNotNull($notifMention);
        $this->assertSame('Alice vous a mentionné', $notifMention->title);
        $this->assertStringContainsString('Alice vous a mentionné dans un commentaire', (string) $notifMention->body);
    }


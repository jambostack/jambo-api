    public function testNotificationSubscriberDispatchesLocalizedEvents(): void
    {
        $notificationService = new NotificationService($this->em, $this->translator);
        $userRepo = $this->createMock(UserRepository::class);

        $subscriber = new NotificationSubscriber($this->em, $userRepo, $notificationService);

        $author = new User();
        $author->id = 1;
        $author->name = 'Charlie';

        $assigned = new User();
        $assigned->id = 2;
        $assigned->locale = 'en';

        $creator = new User();
        $creator->id = 3;
        $creator->locale = 'fr';

        $mentionedUser = new User();
        $mentionedUser->id = 4;
        $mentionedUser->name = 'Dave';
        $mentionedUser->locale = 'en';

        $userRepo->expects($this->once())->method('findOneBy')
            ->with(['name' => 'Dave'])
            ->willReturn($mentionedUser);

        $project = new Project();
        $project->uuid = Uuid::fromString('cccccccc-cccc-cccc-cccc-cccccccccccc');
        $project->id = 100;

        $entry = new ContentEntry();
        $entry->id = 50;
        $entry->status = 'review';
        $entry->locale = 'en';
        $entry->assignedTo = $assigned;
        $entry->createdBy = $creator;
        $entry->project = $project;

        $comment = new Comment();
        $comment->author = $author;
        $comment->entry = $entry;
        $comment->body = 'Great work @Dave !';

        $subscriber->onCommentCreated($comment);

        // Content updated event
        $event = new ContentEvent(ContentEvent::UPDATED, $project, $entry);
        $subscriber->onContentUpdated($event);

        $this->assertSame(['content.updated' => 'onContentUpdated'], NotificationSubscriber::getSubscribedEvents());
    }

    public function testNotificationSubscriberSuppressesSelfNotificationAndUnchangedStatus(): void
    {
        $notificationService = $this->createMock(NotificationService::class);
        $userRepo = $this->createMock(UserRepository::class);

        $subscriber = new NotificationSubscriber($this->em, $userRepo, $notificationService);

        $assignedUser = new User();
        $assignedUser->id = 10;
        $assignedUser->locale = 'en';

        $project = new Project();
        $project->uuid = Uuid::v4();

        $entry = new ContentEntry();
        $entry->id = 99;
        $entry->status = 'review';
        $entry->assignedTo = $assignedUser;
        $entry->updatedBy = $assignedUser; // Same user as assignedTo -> should be suppressed
        $entry->project = $project;

        // notificationService should NEVER be called because user updated their own assigned entry
        $notificationService->expects($this->never())->method('notifyStatusChange');

        $event = new ContentEvent(ContentEvent::UPDATED, $project, $entry);
        $event->previousStatus = 'draft';
        $subscriber->onContentUpdated($event);

        // Second case: different author, but status is unchanged ('review' === 'review')
        $authorUser = new User();
        $authorUser->id = 11;
        $entry->updatedBy = $authorUser;
        $event->previousStatus = 'review'; // Unchanged status -> should be suppressed
        $subscriber->onContentUpdated($event);
    }

    public function testSendNotificationHandlerRequiresRecipientOrResolvesFromContext(): void
    {
        $notificationService = new NotificationService($this->em, $this->translator);
        $userRepo = $this->createMock(UserRepository::class);

        $handler = new SendNotificationHandler($this->em, $notificationService, $userRepo, null, $this->translator);

        // 1. Without recipient -> failure
        $ctx = new FlowContext(automationId: 1, projectUuid: 'dddddddd-dddd-dddd-dddd-dddddddddddd');
        $output = $handler->execute([], $ctx);
        $this->assertFalse($output->data['sent']);
        $this->assertSame('Recipient is required to send notification.', $output->data['error']);

        // 2. With project owner as fallback recipient
        $owner = new User();
        $owner->id = 42;
        $owner->email = 'owner@example.com';
        $owner->locale = 'en';

        $project = new Project();
        $project->owner = $owner;
        $project->uuid = Uuid::fromString('dddddddd-dddd-dddd-dddd-dddddddddddd');
        $ctx->project = $project;

        $outputSuccess = $handler->execute([], $ctx);
        $this->assertTrue($outputSuccess->data['sent']);
        $this->assertSame(42, $outputSuccess->data['recipient_id']);
        $this->assertSame('Automation notification', $outputSuccess->data['title']);

        // 3. With explicit recipient email in config
        $targetUser = new User();
        $targetUser->id = 77;
        $targetUser->email = 'target@example.com';
        $targetUser->name = 'Target User';

        $userRepo->expects($this->once())->method('findOneBy')
            ->with(['email' => 'target@example.com'])
            ->willReturn($targetUser);

        $ctx2 = new FlowContext(1, 'dddddddd-dddd-dddd-dddd-dddddddddddd');
        $ctx2->variables = [
            '_node_config' => [
                'recipient' => 'target@example.com',
                'title'     => 'Custom Workflow Alert',
                'body'      => 'Everything completed fine.',
            ],
        ];
        $ctx2->project = $project;

        $outputTarget = $handler->execute([], $ctx2);
        $this->assertTrue($outputTarget->data['sent']);
        $this->assertSame(77, $outputTarget->data['recipient_id']);
        $this->assertSame('Custom Workflow Alert', $outputTarget->data['title']);
    }

    public function testAuditRetentionServiceIncludesNotificationsPurge(): void
    {
        $auditRepo = $this->createMock(AuditLogRepository::class);
        $webhookRepo = $this->createMock(WebhookLogRepository::class);
        $emailRepo = $this->createMock(EmailLogRepository::class);
        $automationRepo = $this->createMock(AutomationRunRepository::class);
        $notificationRepo = $this->createMock(NotificationRepository::class);

        $auditRepo->expects($this->once())->method('deleteOlderThan')->willReturn(50);
        $webhookRepo->expects($this->once())->method('deleteOlderThan')->willReturn(20);
        $emailRepo->expects($this->once())->method('deleteOlderThan')->willReturn(10);
        $automationRepo->expects($this->once())->method('deleteOlderThan')->willReturn(15);
        $notificationRepo->expects($this->once())->method('deleteReadOlderThan')->willReturn(35);

        $service = new AuditRetentionService(
            auditRepo: $auditRepo,
            webhookRepo: $webhookRepo,
            emailRepo: $emailRepo,
            automationRepo: $automationRepo,
            notificationRepo: $notificationRepo
        );

        $result = $service->purgeLogs(
            auditDays: 90,
            webhookDays: 30,
            emailDays: 30,
            automationDays: 30,
            dryRun: false,
            notificationDays: 60
        );

        $this->assertSame(50, $result['audit']);
        $this->assertSame(20, $result['webhook']);
        $this->assertSame(10, $result['email']);
        $this->assertSame(15, $result['automation']);
        $this->assertSame(35, $result['notification']);
        $this->assertSame(130, $result['total']);
        $this->assertFalse($result['dry_run']);
    }

    public function testNotificationArabicAndSpanishLocalization(): void
    {
        $translator = new class implements TranslatorInterface {
            public function getLocale(): string { return 'en'; }
            public function trans(string $id, array $parameters = [], ?string $domain = null, ?string $locale = null): string
            {
                $ar = require __DIR__ . '/../../translations/messages.ar.php';
                $es = require __DIR__ . '/../../translations/messages.es.php';
                $dict = ($locale === 'ar') ? $ar : (($locale === 'es') ? $es : []);
                return isset($dict[$id]) ? strtr($dict[$id], $parameters) : $id;
            }
        };

        $service = new NotificationService($this->em, $translator);

        $userAr = new User();
        $userAr->id = 100;
        $userAr->locale = 'ar';

        $userEs = new User();
        $userEs->id = 101;
        $userEs->locale = 'es';

        $project = new Project();
        $project->uuid = Uuid::fromString('11111111-2222-3333-4444-555555555555');

        $notifAr = $service->notifyStatusChange($userAr, 'published', 'ar', $project, 1, 1);
        $this->assertSame('تم تغيير الحالة إلى "published"', $notifAr->title);
        $this->assertStringContainsString('الإدخال "ar" أصبح الآن بالحالة "published".', (string) $notifAr->body);

        $notifEs = $service->notifyStatusChange($userEs, 'draft', 'es', $project, 1, 1);
        $this->assertSame('Estado cambiado a "draft"', $notifEs->title);
        $this->assertStringContainsString('La entrada "es" ahora está en estado "draft".', (string) $notifEs->body);
    }

